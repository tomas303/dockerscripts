#!/bin/bash

################################################################################
# launching script (prepare environment for user)                              #
################################################################################

# configure git
gitemail=$(git config --global user.email)
if [ -z "$gitemail" ]; then
  git config --global user.email "$EVDOCKER_GITEMAIL"
fi
gituser=$(git config --global user.name)
if [ -z "$gituser" ]; then
  git config --global user.name "$EVDOCKER_GITUSER"
fi

# build configuration - everything lives in user's home (distrobox home);
# any variable can be overridden by setting it before login
export EVDOCKER_ANDROIDDIR="${EVDOCKER_ANDROIDDIR:-$HOME/android}"
# lineage sources (repo sync here)
export EVDOCKER_LINEAGEDIR="${EVDOCKER_LINEAGEDIR:-$EVDOCKER_ANDROIDDIR/lineage}"
# own signing keys (BACK THEM UP)
export EVDOCKER_KEYSDIR="${EVDOCKER_KEYSDIR:-$EVDOCKER_ANDROIDDIR/keys}"
# signed results (ota zip, signed target files, recovery image)
export EVDOCKER_OUTDIR="${EVDOCKER_OUTDIR:-$EVDOCKER_ANDROIDDIR/signed}"
# lunch target used by signbuild.sh
export EVDOCKER_LUNCH_TARGET="${EVDOCKER_LUNCH_TARGET:-lineage_toco-userdebug}"
# certificate subject of generated keys
export EVDOCKER_CERT_SUBJECT="${EVDOCKER_CERT_SUBJECT:-/C=CZ/ST=Praha/L=Praha/O=Tomas/OU=Tomas/CN=Tomas/emailAddress=tomashorak@post.cz}"
# keys generated by genkeys.sh (testkey is symlinked to releasekey)
export EVDOCKER_KEY_NAMES="${EVDOCKER_KEY_NAMES:-bluetooth cyngn-app media networkstack nfc platform releasekey sdk_sandbox shared testcert verity}"
# key used to sign OTA
export EVDOCKER_OTA_KEY="${EVDOCKER_OTA_KEY:-releasekey}"
# 1 = also generate AVB key (toco can't enroll it, keep 0)
export EVDOCKER_GEN_AVB="${EVDOCKER_GEN_AVB:-0}"
# extra arguments for sign_target_files_apks / ota_from_target_files / mka
export EVDOCKER_SIGN_EXTRA_ARGS="${EVDOCKER_SIGN_EXTRA_ARGS:-}"
export EVDOCKER_OTA_EXTRA_ARGS="${EVDOCKER_OTA_EXTRA_ARGS:-}"
export EVDOCKER_MKA_JOBS="${EVDOCKER_MKA_JOBS:-}"

# configure lineage directory
if [ ! -d "$EVDOCKER_LINEAGEDIR" ]; then
  mkdir -p "$EVDOCKER_LINEAGEDIR"
fi


# add Android SDK platform tools to path
if [ -d "$EVDOCKER_SDKPLATFORMTOOLS" ] ; then
    PATH="$EVDOCKER_SDKPLATFORMTOOLS:$PATH"
fi

export USE_CCACHE=$EVDOCKER_USE_CCACHE
export CCACHE_EXEC=/usr/bin/ccache
ccache -M $EVDOCKER_CCACHE_SIZE

# first droid run creates ccache as empty file(don't know why)
# so this create it in advance
if [ "$USE_CCACHE" == "1" ]; then
  cachetmp="$HOME/.cache/ccache/tmp"
  if [ ! -d "$cachetmp" ]; then
    mkdir -p "$cachetmp"
  fi
fi

export ALLOW_MISSING_DEPENDENCIES=true
export WITH_GMS=true
